"""Create a local, gitignored .env from the hackathon environment.

This script never prints or commits a secret. It understands the Alan Code
environment used by the hackathon account:

  ALAN_CODE_API_KEY               -> ALAN_MODEL_API_KEY
  ALAN_CODE_CONVERSATION_ID       -> ALAN_CONVERSATION_ID
  ALAN_MCP_CREDENTIAL_FILE        -> ALAN_MCP_TOKEN (authorization header)

Usage (from the repository root):
    python scripts/bootstrap_env.py

If a credential is missing, the corresponding key is left blank and the app
reports the missing capability instead of pretending it works.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENV_PATH = ROOT / ".env"


def read_existing() -> dict[str, str]:
    values: dict[str, str] = {}
    if not ENV_PATH.exists():
        return values
    for line in ENV_PATH.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, _, value = stripped.partition("=")
        values[key.strip()] = value.strip()
    return values


def mcp_token() -> str:
    path = os.getenv("ALAN_MCP_CREDENTIAL_FILE", "").strip()
    if not path:
        return ""
    try:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return ""
    authorization = data.get("authorization", "")
    return authorization if isinstance(authorization, str) else ""


def main() -> None:
    existing = read_existing()
    values = {
        # Model gateway (OpenAI-compatible, hackathon credits).
        "ALAN_MODEL_BASE_URL": existing.get(
            "ALAN_MODEL_BASE_URL", "https://api.tryalan.ai/public/harness/v1"
        ),
        "ALAN_MODEL_API_KEY": os.getenv("ALAN_CODE_API_KEY", "").strip()
        or existing.get("ALAN_MODEL_API_KEY", ""),
        "ALAN_MODEL_NAME": existing.get("ALAN_MODEL_NAME", "qwen/qwen3.8-27b"),
        "ALAN_MODEL_FALLBACKS": existing.get(
            "ALAN_MODEL_FALLBACKS", "nvidia/nemotron-3-super-120b-a12b"
        ),
        "ALAN_MODEL_TIMEOUT_SECONDS": existing.get("ALAN_MODEL_TIMEOUT_SECONDS", "90"),
        "ALAN_CONVERSATION_ID": os.getenv("ALAN_CODE_CONVERSATION_ID", "").strip()
        or existing.get("ALAN_CONVERSATION_ID", ""),
        # Alan MCP (optional workflow escalation).
        "ALAN_MCP_URL": existing.get("ALAN_MCP_URL", "https://api.tryalan.ai/mcp"),
        "ALAN_MCP_TOKEN": mcp_token() or existing.get("ALAN_MCP_TOKEN", ""),
        "ALAN_WORKFLOW_ID": existing.get("ALAN_WORKFLOW_ID", ""),
        "ALAN_TIMEOUT_SECONDS": existing.get("ALAN_TIMEOUT_SECONDS", "300"),
        "ALAN_POLL_SECONDS": existing.get("ALAN_POLL_SECONDS", "3"),
        # Demo controls.
        "DOCUPILOT_AUTO_SEED": existing.get("DOCUPILOT_AUTO_SEED", "true"),
        "DOCUPILOT_MAX_UPLOAD_MB": existing.get("DOCUPILOT_MAX_UPLOAD_MB", "10"),
    }

    lines = [
        "# Local DocuPilot AI configuration. GITIGNORED. Never commit this file.",
        "# Generated by scripts/bootstrap_env.py; secrets are read from the environment.",
        "",
        "ALAN_MODEL_BASE_URL=" + values["ALAN_MODEL_BASE_URL"],
        "ALAN_MODEL_API_KEY=" + values["ALAN_MODEL_API_KEY"],
        "ALAN_MODEL_NAME=" + values["ALAN_MODEL_NAME"],
        "ALAN_MODEL_FALLBACKS=" + values["ALAN_MODEL_FALLBACKS"],
        "ALAN_MODEL_TIMEOUT_SECONDS=" + values["ALAN_MODEL_TIMEOUT_SECONDS"],
        "ALAN_CONVERSATION_ID=" + values["ALAN_CONVERSATION_ID"],
        "",
        "ALAN_MCP_URL=" + values["ALAN_MCP_URL"],
        "ALAN_MCP_TOKEN=" + values["ALAN_MCP_TOKEN"],
        "ALAN_WORKFLOW_ID=" + values["ALAN_WORKFLOW_ID"],
        "ALAN_TIMEOUT_SECONDS=" + values["ALAN_TIMEOUT_SECONDS"],
        "ALAN_POLL_SECONDS=" + values["ALAN_POLL_SECONDS"],
        "",
        "DOCUPILOT_AUTO_SEED=" + values["DOCUPILOT_AUTO_SEED"],
        "DOCUPILOT_MAX_UPLOAD_MB=" + values["DOCUPILOT_MAX_UPLOAD_MB"],
        "",
    ]
    ENV_PATH.write_text("\n".join(lines), encoding="utf-8")

    print("wrote .env (values not displayed)")
    print("model configured:", bool(values["ALAN_MODEL_API_KEY"]))
    print("conversation header configured:", bool(values["ALAN_CONVERSATION_ID"]))
    print("MCP token configured:", bool(values["ALAN_MCP_TOKEN"]))
    print("workflow configured:", bool(values["ALAN_WORKFLOW_ID"]))


if __name__ == "__main__":
    main()